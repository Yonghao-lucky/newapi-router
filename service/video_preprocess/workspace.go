package video_preprocess

import (
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"sync"
	"time"
)

// workspacePrefix marks the directories this package owns under Limits.TempRoot.
// CleanupStale only ever removes directories carrying this prefix, so a
// misconfigured temp root cannot turn into a recursive delete of unrelated
// files.
const workspacePrefix = "vp-"

// maxStaleScanEntries bounds how many directory entries one CleanupStale call
// inspects, so a polluted temp root cannot stall a background janitor.
const maxStaleScanEntries = 10_000

// workspace is the request-scoped temporary directory for one video. Paths are
// generated by the engine; no client-controlled string ever reaches a path
// component.
type workspace struct {
	dir string

	mu     sync.Mutex
	closed bool
	files  int64
	bytes  int64
}

// newWorkspace creates a private request-scoped directory under root. The
// directory is created 0700 and every file inside it is created 0600, so media
// is never readable by another local user.
func newWorkspace(root string) (*workspace, error) {
	if err := os.MkdirAll(root, 0o700); err != nil {
		return nil, wrapError(CodeStorageFailed, "failed to prepare the video preprocessing temp root", err)
	}
	dir, err := os.MkdirTemp(root, workspacePrefix)
	if err != nil {
		return nil, wrapError(CodeStorageFailed, "failed to create a video preprocessing workspace", err)
	}
	if err := os.Chmod(dir, 0o700); err != nil {
		_ = os.RemoveAll(dir)
		return nil, wrapError(CodeStorageFailed, "failed to secure the video preprocessing workspace", err)
	}
	return &workspace{dir: dir}, nil
}

// path returns an absolute path inside the workspace. The suffix is always a
// constant supplied by the engine.
func (w *workspace) path(suffix string) string {
	return filepath.Join(w.dir, suffix)
}

// create opens a new 0600 file inside the workspace. The engine only ever
// chooses literal suffixes, but the check keeps a future caller from escaping
// the workspace if that ever changes.
func (w *workspace) create(name string) (*os.File, error) {
	clean := filepath.Clean(name)
	if clean == "." || filepath.IsAbs(clean) || strings.Contains(clean, string(filepath.Separator)) {
		return nil, invalidConfig("workspace file name must be a plain name, got %q", name)
	}
	f, err := os.OpenFile(w.path(clean), os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o600)
	if err != nil {
		return nil, wrapError(CodeStorageFailed, "failed to create a workspace file", err)
	}
	return f, nil
}

// remove deletes a single file inside the workspace. It is idempotent.
func (w *workspace) remove(name string) error {
	err := os.Remove(w.path(name))
	if err == nil || errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	return err
}

// bytesOnDisk reports the current size of the workspace's files by walking its
// directory. A workspace deleted concurrently reports zero; read errors on
// individual entries are skipped, because the gauge is advisory and a missing
// file no longer occupies space.
func (w *workspace) bytesOnDisk() int64 {
	if w == nil {
		return 0
	}
	var total int64
	entries, err := os.ReadDir(w.dir)
	if err != nil {
		return 0
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		if info, err := entry.Info(); err == nil {
			total += info.Size()
		}
	}
	return total
}

// Cleanup removes the workspace and everything inside it. It is idempotent and
// safe to call concurrently, so a request path, its deferred cleanup and a
// cancellation handler can all invoke it without coordination.
func (w *workspace) Cleanup() error {
	if w == nil {
		return nil
	}
	w.mu.Lock()
	defer w.mu.Unlock()
	if w.closed {
		return nil
	}
	w.closed = true
	if err := os.RemoveAll(w.dir); err != nil {
		return wrapError(CodeStorageFailed, "failed to remove the video preprocessing workspace", err)
	}
	return nil
}

// CleanupStale removes workspaces under root that were abandoned by a crash or
// a restart. A workspace is stale once its modification time is older than ttl.
//
// Only directories named vp-* directly under root are considered, so the call
// cannot delete anything this package did not create. The sweep never fails
// the caller: leftover media is an operational nuisance, not a request error.
func CleanupStale(root string, ttl time.Duration) error {
	if root == "" {
		root = DefaultTempRoot
	}
	if ttl <= 0 {
		return invalidConfig("stale file ttl must be positive")
	}
	entries, err := os.ReadDir(root)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return err
	}

	cutoff := time.Now().Add(-ttl)
	for i, entry := range entries {
		if i >= maxStaleScanEntries {
			break
		}
		if !entry.IsDir() || !strings.HasPrefix(entry.Name(), workspacePrefix) {
			continue
		}
		info, err := entry.Info()
		if err != nil {
			continue
		}
		if info.ModTime().After(cutoff) {
			continue
		}
		_ = os.RemoveAll(filepath.Join(root, entry.Name()))
	}
	return nil
}

// isWorkspaceName reports whether name is one this package may own. It exists
// so tests can assert the cleanup namespace without duplicating the prefix.
func isWorkspaceName(name string) bool {
	if !strings.HasPrefix(name, workspacePrefix) {
		return false
	}
	// os.MkdirTemp appends a random base-36-ish suffix to the pattern.
	suffix := strings.TrimPrefix(name, workspacePrefix)
	if suffix == "" {
		return false
	}
	for i := 0; i < len(suffix); i++ {
		c := suffix[i]
		if (c < '0' || c > '9') && (c < 'a' || c > 'z') {
			return false
		}
	}
	return true
}

// parseWorkspacePID is unused by the engine but keeps the door open for a
// future pid-tagged workspace scheme; it is deliberately not exported.
func parseWorkspacePID(name string) (int, bool) {
	_, rest, ok := strings.Cut(name, workspacePrefix)
	if !ok {
		return 0, false
	}
	pidPart, _, ok := strings.Cut(rest, "-")
	if !ok {
		return 0, false
	}
	pid, err := strconv.Atoi(pidPart)
	if err != nil {
		return 0, false
	}
	return pid, true
}
